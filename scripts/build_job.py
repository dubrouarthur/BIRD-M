"""Build a self-contained Hugging Face Jobs script (no token needed inside the job).

The job script embeds our code (zip, base64), regenerates the training data deterministically
(same seeds as the published datasets), trains and evaluates, and prints the report in the logs.

Usage:
  python scripts/build_job.py --model Qwen/Qwen3.8-27B --out dist/job_27b.py
  hf jobs uv run --flavor h200 --timeout 1h45m dist/job_27b.py
"""

import argparse
import base64
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = [
    "bird_m",
    "data/skills",
    "scripts/train_sft.py",
    "scripts/eval_bsp.py",
    "scripts/gen_finance.py",
    "scripts/gen_skills.py",
]

ap = argparse.ArgumentParser()
ap.add_argument("--model", default="Qwen/Qwen3.8-27B")
ap.add_argument("--epochs", default="1")
ap.add_argument("--lr", default="1e-4")
ap.add_argument("--batch-tokens", default="16384")
ap.add_argument("--n-skills", default="150")
ap.add_argument("--n-fin", default="40")
ap.add_argument("--out", required=True)
ap.add_argument("--run-dir", default="runs/pilot", help="e.g. /ckpt/<run> with a bucket mounted at /ckpt")
a = ap.parse_args()

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    for inc in INCLUDE:
        p = ROOT / inc
        files = (
            [p]
            if p.is_file()
            else [
                f for f in p.rglob("*") if f.is_file() and "__pycache__" not in f.parts
            ]
        )
        for f in files:
            z.write(f, f.relative_to(ROOT))
blob = base64.b64encode(buf.getvalue()).decode()

job = f'''# /// script
# requires-python = ">=3.11"
# dependencies = ["torch", "transformers>=5.2", "peft>=0.21", "accelerate", "pyyaml", "jsonschema", "flash-linear-attention"]
# ///
"""BIRD-M training job (generated by scripts/build_job.py). Model: {a.model}."""
import base64, io, os, subprocess, sys, time, zipfile

W = "/tmp/birdm"
zipfile.ZipFile(io.BytesIO(base64.b64decode("{blob}"))).extractall(W)
os.chdir(W)
env = dict(os.environ, PYTHONPATH=W, PYTHONUNBUFFERED="1")


def run(*cmd):
    t = time.time()
    print(">>>", " ".join(cmd), flush=True)
    r = subprocess.run([sys.executable, *cmd], env=env)
    print(f"<<< exit={{r.returncode}} secs={{round(time.time() - t)}}", flush=True)
    if r.returncode:
        sys.exit(r.returncode)


subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])
run("scripts/gen_skills.py", "--n", "3000", "--seed", "0", "--split", "train", "--out", "data/out/skills_pilot.jsonl")
run("scripts/gen_finance.py", "--n", "2000", "--seed", "0", "--out", "data/out/finance_pilot.jsonl")
run("scripts/train_sft.py", "--model", "{a.model}", "--data", "data/out/skills_pilot.jsonl", "data/out/finance_pilot.jsonl",
    "--out", "{a.run_dir}", "--epochs", "{a.epochs}", "--lr", "{a.lr}", "--batch-tokens", "{a.batch_tokens}", "--max-len", "2048")
run("scripts/eval_bsp.py", "--model", "{a.model}", "--adapter", "{a.run_dir}/adapter", "--n-skills", "{a.n_skills}",
    "--n-fin", "{a.n_fin}", "--max-new", "450", "--out", "{a.run_dir}/eval.json")
'''
out = Path(a.out)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(job, encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size // 1024} KiB)")
